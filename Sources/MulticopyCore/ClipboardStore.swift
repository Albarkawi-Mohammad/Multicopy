import AppKit
import Foundation

public final class ClipboardStore: ObservableObject {
    public struct Item: Identifiable, Codable, Equatable {
        public let id: UUID
        public var text: String
        public var createdAt: Date
        public var isPinned: Bool

        public init(id: UUID = UUID(), text: String, createdAt: Date = Date(), isPinned: Bool = false) {
            self.id = id
            self.text = text
            self.createdAt = createdAt
            self.isPinned = isPinned
        }

        public var preview: String {
            let normalized = text
                .replacingOccurrences(of: "\r\n", with: "\n")
                .trimmingCharacters(in: .whitespacesAndNewlines)
            if normalized.count > 500 {
                return String(normalized.prefix(500)) + "\u{2026}"
            }
            return normalized
        }
    }

    @Published public private(set) var items: [Item] = []

    public let maxUnpinnedItems: Int

    private let fileURL: URL
    private let pasteboard: NSPasteboard
    private var lastChangeCount = -1
    private var timer: Timer?
    private var isMonitoring = false

    public init(
        fileURL: URL? = nil,
        maxUnpinnedItems: Int = 200,
        pasteboard: NSPasteboard = .general
    ) {
        self.fileURL = fileURL ?? Self.defaultFileURL
        self.maxUnpinnedItems = maxUnpinnedItems
        self.pasteboard = pasteboard
        load()
    }

    deinit {
        timer?.invalidate()
    }

    public static var defaultFileURL: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base
            .appendingPathComponent("Multicopy", isDirectory: true)
            .appendingPathComponent("history.json")
    }

    public func startMonitoring(interval: TimeInterval = 0.45) {
        guard !isMonitoring else { return }
        isMonitoring = true
        lastChangeCount = pasteboard.changeCount

        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public func stopMonitoring() {
        timer?.invalidate()
        timer = nil
        isMonitoring = false
    }

    public func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard !isConcealed(pasteboard) else { return }
        guard let text = pasteboard.string(forType: .string) else { return }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        ingest(text)
    }

    public func ingest(_ text: String, at date: Date = Date()) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        if let index = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: index)
            item.createdAt = date
            items.append(item)
        } else {
            items.append(Item(text: text, createdAt: date))
        }

        prune()
        save()
    }

    public func visibleItems(query: String = "") -> [Item] {
        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        let filtered = trimmed.isEmpty
            ? items
            : items.filter { $0.text.localizedCaseInsensitiveContains(trimmed) }

        return filtered.sorted { lhs, rhs in
            if lhs.isPinned != rhs.isPinned {
                return lhs.isPinned
            }
            return lhs.createdAt > rhs.createdAt
        }
    }

    public func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isPinned.toggle()
        save()
    }

    public func delete(_ id: UUID) {
        items.removeAll { $0.id == id }
        save()
    }

    public func clearUnpinned() {
        items.removeAll { !$0.isPinned }
        save()
    }

    public func copyToPasteboard(_ item: Item) {
        copyToPasteboard(item.text)
    }

    public func copyToPasteboard(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    public func saveNow() {
        save()
    }

    private func isConcealed(_ pasteboard: NSPasteboard) -> Bool {
        let concealedTypes = [
            "org.nspasteboard.TransientType",
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.AutoGeneratedType",
            "de.petermaurer.TransientPasteboardType",
            "com.agilebits.onepassword",
            "com.typeit4me.clipping"
        ]

        guard let types = pasteboard.types else { return false }
        return types.contains { concealedTypes.contains($0.rawValue) }
    }

    private func prune() {
        let unpinned = items
            .filter { !$0.isPinned }
            .sorted { $0.createdAt > $1.createdAt }
        let retained = Set(unpinned.prefix(maxUnpinnedItems).map(\.id))
        items.removeAll { !$0.isPinned && !retained.contains($0.id) }
    }

    private func save() {
        do {
            let directory = fileURL.deletingLastPathComponent()
            try FileManager.default.createDirectory(
                at: directory,
                withIntermediateDirectories: true
            )
            try? FileManager.default.setAttributes(
                [.posixPermissions: 0o700],
                ofItemAtPath: directory.path
            )

            let data = try JSONEncoder().encode(items)
            try data.write(to: fileURL, options: .atomic)
            try? FileManager.default.setAttributes(
                [.posixPermissions: 0o600],
                ofItemAtPath: fileURL.path
            )
        } catch {
            NSLog("Multicopy: could not save history: \(error.localizedDescription)")
        }
    }

    private func load() {
        guard
            let data = try? Data(contentsOf: fileURL),
            let stored = try? JSONDecoder().decode([Item].self, from: data)
        else {
            return
        }

        items = stored
        prune()
    }
}
